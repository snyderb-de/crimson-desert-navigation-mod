#include "destination_session.hpp"
#include <iostream>
int main(){
    using namespace crimson_nav;
    int failures=0,checks=0;auto check=[&](bool ok,const char *label){++checks;if(!ok){++failures;std::cerr<<"FAIL: "<<label<<'\n';}};
    TargetState present;present.status=TargetStatus::candidate;present.address=0x10000;
    present.xyz[0]=100;present.xyz[1]=50;present.xyz[2]=200;
    TargetState absent;absent.status=TargetStatus::no_candidate;
    TargetState ambiguous;ambiguous.status=TargetStatus::ambiguous;
    MapState state{};state.destination_ui_valid=true;state.destination_candidate=true;
    state.distance_valid=true;state.distance=224;
    DestinationSession session;
    check(!session.update({},state,true,false,0).active,"fresh unknown state never invents a route");
    check(!session.update(absent,state,true,false,100).active,"fresh empty state never invents a route");
    check(session.update(present,state,true,false,200).active,"valid destination starts navigation");
    auto held=session.update({},state,false,false,100000);
    check(held.active&&held.retained&&held.target.xyz[0]==100,"unknown observations never time out the route");
    check(session.update(ambiguous,state,true,false,100100).active,"ambiguity preserves previous destination");
    check(session.update(absent,state,true,false,100200).active,"missing icon with active label is not removal");
    state.destination_candidate=false;
    check(session.update(absent,state,true,false,100300).active,"speech or combat absence far from destination preserves route");
    check(session.update(absent,state,true,false,200000).active,"long interruption is not a cancellation timeout");
    check(session.update(absent,state,false,true,200100).active,"opening full map after interruption does not invent removal");
    state.destination_candidate=true;session.update(present,state,false,true,200200);
    state.destination_candidate=false;
    check(session.update(absent,state,false,true,200300).active,"one clear observation is insufficient");
    check(session.update({},state,false,false,200400).active,"unknown map state interrupts clear confirmation");
    check(session.update(absent,state,false,true,201000).active,"full map must see destination again after interruption");
    state.destination_candidate=true;session.update(present,state,false,true,201100);
    state.destination_candidate=false;
    check(session.update(absent,state,false,true,201200).active,"fresh clear starts confirmation");
    check(!session.update(absent,state,false,true,201400).active,"coherent full-map clear ends route");
    check(!session.update({},state,false,false,300000).active,"ended route cannot return from cached state");
    state.destination_candidate=true;
    check(session.update(present,state,true,false,300100).active,"same destination can be selected again");
    auto other=present;other.address=0x20000;other.xyz[0]=500;
    check(session.update(other,state,true,false,300200).target.xyz[0]==500,"new destination replaces remembered target");
    auto moved=other;moved.xyz[0]=500.01f;
    check(session.update(moved,state,true,false,300300).target.xyz[0]==moved.xyz[0],"small real coordinate updates retained");
    check(session.update(other,state,true,false,900000).active,"time alone never completes route");
    for(unsigned i=0;i<3;++i)state.xyz[i]=other.xyz[i];state.distance=0;
    check(session.update(other,state,true,false,900100).active,"proximity alone does not complete active destination");
    state.destination_candidate=false;
    check(session.update(absent,state,true,false,900200).active,"game arrival clear starts confirmation");
    check(!session.update(absent,state,true,false,900400).active,"game clear at actual destination completes route");
    state.destination_candidate=true;session.update(other,state,true,false,901000);
    state.destination_candidate=false;state.xyz[0]=0;
    session.update(absent,state,true,false,901100);
    check(session.update(absent,state,true,false,901300).active,"road endpoint far from actual destination cannot complete route");
    state.xyz[0]=500;state.xyz[1]=100;
    session.update(absent,state,true,false,901400);
    check(session.update(absent,state,true,false,901600).active,"different known elevation does not corroborate arrival");
    state.xyz[1]=50;state.distance_valid=false;
    session.update(absent,state,true,false,901700);
    check(session.update(absent,state,true,false,901900).active,"invalid distance cannot corroborate arrival");
    state.distance_valid=true;state.destination_ui_valid=false;
    session.update(absent,state,true,false,902000);
    check(session.update(absent,state,true,false,902200).active,"invalid label cannot corroborate arrival");
    DestinationSession quick_close;MapState clear_state{};
    clear_state.destination_ui_valid=true;clear_state.destination_candidate=true;
    quick_close.update(present,clear_state,false,true,100);
    clear_state.destination_candidate=false;
    quick_close.update(absent,clear_state,false,true,200);
    check(!quick_close.update(absent,clear_state,true,false,400).active,"closing full map after removal does not cancel clear confirmation");
    DestinationSession gap;clear_state.destination_candidate=true;
    gap.update(present,clear_state,false,true,100);clear_state.destination_candidate=false;
    gap.update(absent,clear_state,false,true,200);gap.update(absent,clear_state,true,false,10000);
    check(gap.update(absent,clear_state,true,false,10200).active,"old full-map clear evidence expires across sampling gap");
    DestinationSession old_arm;clear_state.destination_candidate=true;
    old_arm.update(present,clear_state,false,true,100);clear_state.destination_candidate=false;
    old_arm.update(absent,clear_state,false,true,10000);
    check(old_arm.update(absent,clear_state,false,true,10200).active,"full-map arming expires across sampling gap");
    if(!failures)std::cout<<"PASS: "<<checks<<" destination lifecycle cases\n";
    return failures?1:0;
}
